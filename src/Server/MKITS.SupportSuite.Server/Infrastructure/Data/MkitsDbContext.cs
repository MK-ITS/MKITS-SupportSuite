using Microsoft.AspNetCore.Identity;
using Microsoft.AspNetCore.Identity.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;
using MKITS.SupportSuite.Server.Features.Audit;
using MKITS.SupportSuite.Server.Features.Identity;
using MKITS.SupportSuite.Server.Features.IpBans;

namespace MKITS.SupportSuite.Server.Infrastructure.Data;

/// <summary>
/// The server database (SQLite, ADR-0006). Schema changes are made only through EF Core migrations
/// in <c>Infrastructure/Data/Migrations</c> (generated by the "EF migration" workflow, see docs/development.md).
/// </summary>
public sealed class MkitsDbContext(DbContextOptions<MkitsDbContext> options)
    : IdentityDbContext<MkitsUser, IdentityRole<Guid>, Guid>(options)
{
    public DbSet<AuditEvent> AuditEvents => Set<AuditEvent>();

    public DbSet<IpBan> IpBans => Set<IpBan>();

    public DbSet<IpListEntry> IpListEntries => Set<IpListEntry>();

    protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder)
    {
        ArgumentNullException.ThrowIfNull(configurationBuilder);

        // SQLite has no native DateTimeOffset type; storing as binary (UTC ticks + offset) keeps
        // comparisons and ORDER BY translatable to SQL. Applies to nullable properties as well.
        configurationBuilder.Properties<DateTimeOffset>().HaveConversion<DateTimeOffsetToBinaryConverter>();
    }

    protected override void OnModelCreating(ModelBuilder builder)
    {
        ArgumentNullException.ThrowIfNull(builder);

        base.OnModelCreating(builder);

        builder.Entity<MkitsUser>(user =>
        {
            user.Property(u => u.DisplayName).HasMaxLength(100).IsRequired();
            user.Property(u => u.UiCulture).HasMaxLength(10);
        });

        builder.Entity<AuditEvent>(audit =>
        {
            audit.ToTable("AuditEvents");
            audit.HasKey(a => a.Id);
            audit.Property(a => a.Id).ValueGeneratedOnAdd();
            audit.Property(a => a.EventType).HasMaxLength(100).IsRequired();
            audit.Property(a => a.ActorId).HasMaxLength(100);
            audit.Property(a => a.Ip).HasMaxLength(64);
            audit.Property(a => a.TargetType).HasMaxLength(50);
            audit.Property(a => a.TargetId).HasMaxLength(100);
            audit.Property(a => a.PreviousHash).HasMaxLength(32).IsRequired();
            audit.Property(a => a.Hash).HasMaxLength(32).IsRequired();
            audit.HasIndex(a => a.Timestamp);
            audit.HasIndex(a => a.EventType);
        });

        builder.Entity<IpBan>(ban =>
        {
            ban.ToTable("IpBans");
            ban.Property(b => b.Network).HasMaxLength(64).IsRequired();
            ban.Property(b => b.Reason).HasMaxLength(200).IsRequired();
            ban.HasIndex(b => b.Network);
            ban.HasIndex(b => b.ExpiresAt);
        });

        builder.Entity<IpListEntry>(entry =>
        {
            entry.ToTable("IpListEntries");
            entry.Property(e => e.Network).HasMaxLength(64).IsRequired();
            entry.Property(e => e.Comment).HasMaxLength(200);
            entry.HasIndex(e => new { e.ListType, e.Network }).IsUnique();
        });
    }
}
