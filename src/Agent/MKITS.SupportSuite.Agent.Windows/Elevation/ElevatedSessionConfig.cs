using System.Globalization;
using System.Security.AccessControl;
using System.Security.Principal;
using System.Text.Json;

namespace MKITS.SupportSuite.Agent.Windows.Elevation;

/// <summary>
/// Parameters of one elevated ad-hoc session, written by the elevated installer into a folder only SYSTEM and
/// Administrators can access, and read by the temporary service and the helper. Never contains secrets of the
/// session itself (codes, tokens, keys).
/// </summary>
internal sealed record ElevatedSessionConfig(string Id, string PipeName, int ClientProcessId, string UserSid)
{
    private static readonly JsonSerializerOptions Json = new() { WriteIndented = false };

    /// <summary>Service names use this prefix plus the id, e.g. <c>MKITSSupport-3f2a…</c>.</summary>
    public const string ServicePrefix = "MKITSSupport-";

    public string ServiceName => ServicePrefix + Id;

    /// <summary><c>%ProgramData%\MKITS-SupportSuite\adhoc\&lt;id&gt;</c>.</summary>
    public static string DirectoryFor(string id) =>
        Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.CommonApplicationData), "MKITS-SupportSuite", "adhoc", id);

    public static string ExecutableFor(string id) => Path.Combine(DirectoryFor(id), "MKITS-Support.exe");

    /// <summary>Ids are generated by the client: 32 hex characters (a GUID). Anything else is rejected (no path tricks).</summary>
    public static bool IsValidId(string? id) => id is { Length: 32 } && id.All(char.IsAsciiHexDigit);

    public static ElevatedSessionConfig Load(string id)
    {
        if (!IsValidId(id))
        {
            throw new ArgumentException("Invalid session id.", nameof(id));
        }

        var config = JsonSerializer.Deserialize<ElevatedSessionConfig>(File.ReadAllText(Path.Combine(DirectoryFor(id), "session.json")), Json)
            ?? throw new InvalidDataException("Empty configuration.");
        return config.Id == id ? config : throw new InvalidDataException("Configuration does not match the id.");
    }

    /// <summary>Creates the protected folder (SYSTEM and Administrators only) and writes the configuration.</summary>
    public void Save()
    {
        var directory = DirectoryFor(Id);
        var security = new DirectorySecurity();
        security.SetAccessRuleProtection(isProtected: true, preserveInheritance: false);
        foreach (var sid in new[] { WellKnownSidType.LocalSystemSid, WellKnownSidType.BuiltinAdministratorsSid })
        {
            security.AddAccessRule(new FileSystemAccessRule(
                new SecurityIdentifier(sid, null), FileSystemRights.FullControl,
                InheritanceFlags.ContainerInherit | InheritanceFlags.ObjectInherit, PropagationFlags.None, AccessControlType.Allow));
        }

        // Read access for everyone else would let users read the pipe name early; not needed – deny by omission.
        Directory.CreateDirectory(Path.GetDirectoryName(directory)!);
        new DirectoryInfo(directory).Create(security);
        File.WriteAllText(Path.Combine(directory, "session.json"), JsonSerializer.Serialize(this, Json));
    }

    public override string ToString() => string.Create(CultureInfo.InvariantCulture, $"{Id} (client {ClientProcessId})");
}
